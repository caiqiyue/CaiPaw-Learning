#!/bin/bash
# ============================================================
# PreToolUse 护栏：硬约束 L2 —— 「一步不许太大」
# ============================================================
# 为什么需要它：
#   L2 原本只写在 AGENTS.md 里（防线 2 · 文件层）。但 AI 天然倾向
#   「一次给全」，光写在文档里约束力太弱。本 hook 是**防线 3 · Hook 层**，
#   系统强制，不靠自觉。
#
# 判据：单次写入内容的行数 > 阈值 → 拦截（exit 2），把提示回灌给 AI。
#
# ★ 设计原则：**fail-open** —— 解析不出来一律放行。
#   护栏误伤比漏报更糟：挡住正常干活，人会直接把护栏关掉，那就全废了。
#
# 放宽阈值：CAIPAW_STEP_MAX_LINES=800 ./init.sh
# 关掉本 hook：临时把 .claude/settings.json 里这条删掉即可
# ============================================================

THRESHOLD=${CAIPAW_STEP_MAX_LINES:-300}

INPUT=$(cat)

# JSON 字符串里换行被转义成字面量 \n（两个字符），
# 所以整个 content 落在同一行上，数 \n 的出现次数即可近似得到行数。
#
# ⚠️ 这里刻意**只用 bash 内建**做计数，不调 grep / sed：
#    不同 grep 实现对 '\\n' 的解释不一致（git-bash 的 grep 会把它当成
#    真正的换行符），用外部工具会让这道护栏在不同机器上行为不同。
#
# 两步删除，顺序不能反：
#   1. 先删「转义的反斜杠」\\ —— 否则 Windows 路径里的 \notes 会被当成 \n 而幻影计数
#   2. 再删「转义的换行」\n
#   长度差 / 2 = \n 出现次数；N 个换行 = N+1 行，所以 +1。
CLEAN=${INPUT//\\\\/}
STRIPPED=${CLEAN//\\n/}
COUNT=$(( ( ${#CLEAN} - ${#STRIPPED} ) / 2 + 1 ))

# 兜底：非数字 → 放行
case "$COUNT" in
  ''|*[!0-9]*) exit 0 ;;
esac

if [ "$COUNT" -gt "$THRESHOLD" ]; then
  cat >&2 <<EOF
🚧 L2 拦截：这次写入约 $COUNT 行，超过阈值 $THRESHOLD 行。

「一步」的定义（docs/核心宗旨.md §2）：
  一次会话内能完成 · 能立刻跑起来 · 50~200 行 · 1~2 个新概念

三个「太大」信号，命中任一就该拆（docs/核心宗旨.md §2.2）：
  1. 超过 300 行
  2. 超过 3 个文件
  3. 做完不能立刻看到结果

请拆成两步：先做能立刻跑起来的最小一半，跑通、让用户看过、写完笔记，再继续。

（确需一次性写入大段内容时，用 CAIPAW_STEP_MAX_LINES=<更大值> 放宽）
EOF
  exit 2
fi

exit 0
